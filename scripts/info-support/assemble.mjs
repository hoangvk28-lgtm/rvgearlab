// Validates written support articles and regenerates the two data files.
// Only slugs with BOTH public/content/informational/<slug>.md and meta/<slug>.json are published.
// Usage: node scripts/info-support/assemble.mjs [--strict]   (strict: exit 1 on any error)
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const dir = path.join(root, "scripts/info-support");
const plan = JSON.parse(fs.readFileSync(path.join(dir, "plan.json"), "utf8"));
const images = fs.existsSync(path.join(dir, "images.json")) ? JSON.parse(fs.readFileSync(path.join(dir, "images.json"), "utf8")) : {};
const mdDir = path.join(root, "public/content/informational");

// Every internal href the site can resolve
const reg = fs.readFileSync(path.join(root, "data/guides.ts"), "utf8");
const valid = new Set();
for (const m of reg.matchAll(/slug: "([^"]+)"[\s\S]*?subcategorySlug: "([^"]+)"/g)) valid.add(`/${m[2]}/${m[1]}`);
const infoTxt = fs.readFileSync(path.join(root, "data/informational-guides.ts"), "utf8") + fs.readFileSync(path.join(root, "data/informational-guides.camping.generated.ts"), "utf8");
for (const m of infoTxt.matchAll(/"slug": "([^"]+)",\s*"silo": "([^"]+)"/g)) valid.add(`/${m[2]}/${m[1]}`);
for (const t of plan) valid.add(`/${t.silo}/${t.slug}`);
for (const s of ["/how-we-review", "/affiliate-disclosure", "/about"]) valid.add(s);

const LEAK = /we tested|we tried|in our lab|we measured|not stated in the text|the excerpt|facts provided|not listed in the features|candidates we reviewed|the pool\b/i;
const entries = [], reverse = {}, report = [];
let errors = 0;
for (const t of plan) {
  const md = path.join(mdDir, `${t.slug}.md`), metaF = path.join(dir, "meta", `${t.slug}.json`);
  if (!fs.existsSync(md) || !fs.existsSync(metaF)) continue;
  const body = fs.readFileSync(md, "utf8");
  const meta = JSON.parse(fs.readFileSync(metaF, "utf8"));
  const errs = [];
  const prose = body.replace(/!\[[^\]]*\]\([^)]*\)/g, "").replace(/\]\([^)]*\)/g, "]");
  const words = prose.split(/\s+/).filter((w) => /[a-z0-9]/i.test(w)).length;
  if (words < 2700 || words > 3300) errs.push(`words ${words}`);
  if (/[–—]/.test(body + JSON.stringify(meta))) errs.push("em/en dash");
  if (LEAK.test(body)) errs.push(`leak/claim: ${body.match(LEAK)[0]}`);
  if (!/^# /.test(body)) errs.push("missing H1");
  if (!/^## (Frequently asked questions|FAQ)/im.test(body)) errs.push("no FAQ section");
  if (!/^## Image credits/im.test(body)) errs.push("no Image credits section");
  const imgs = [...body.matchAll(/!\[([^\]]*)\]\(([^)]+)\)/g)];
  if (imgs.length < 1) errs.push(`images ${imgs.length}`);
  if (imgs.some((i) => !i[1].trim())) errs.push("image without alt");
  const known = new Set((images[t.slug] ?? []).map((i) => i.src));
  const local = (s) => s.startsWith(`/images/info/${t.slug}-`) && fs.existsSync(path.join(root, "public", s));
  if (imgs.some((i) => !known.has(i[2]) && !local(i[2]))) errs.push("image not from images.json / not localized");
  if (imgs.some((i) => /^https?:/.test(i[2]))) errs.push("remote image not localized");
  const links = [...body.replace(/!\[[^\]]*\]\([^)]*\)/g, "").matchAll(/\]\((\/[^)#\s]*)/g)].map((m) => m[1]);
  const bad = links.filter((h) => !valid.has(h));
  if (bad.length) errs.push(`broken links: ${bad.join(" ")}`);
  const moneyIn = links.filter((h) => t.moneyPages.some((m) => m.href === h)).length;
  if (moneyIn < 4) errs.push(`only ${moneyIn} in-body Best links`);
  if (links.length - moneyIn < 2) errs.push(`only ${links.length - moneyIn} in-body info links`);
  if (!meta.metaTitle || meta.metaTitle.length > 46) errs.push(`metaTitle ${meta.metaTitle?.length}`);
  if (!meta.description || meta.description.length < 120 || meta.description.length > 160) errs.push(`description ${meta.description?.length}`);
  if (!meta.directAnswer) errs.push("no directAnswer");
  report.push(`${errs.length ? "FAIL" : "ok  "} ${t.slug} (${words}w, ${links.length} links, ${imgs.length} img)${errs.length ? " :: " + errs.join("; ") : ""}`);
  if (errs.length) { errors++; continue; }
  entries.push({
    slug: t.slug, silo: t.silo, title: body.match(/^# (.+)$/m)[1].trim(), metaTitle: meta.metaTitle, description: meta.description,
    dek: meta.directAnswer, directAnswer: meta.directAnswer, readTime: `${Math.round(words / 230)} min`, lastUpdated: meta.lastUpdated ?? "2026-11-17",
    keyTakeaways: [], sections: [], faq: [], sources: [], related: t.relatedInfo,
    contentFile: `${t.slug}.md`, heroImage: imgs[0][2], moneyPages: t.moneyPages,
  });
  for (const m of t.moneyPages) (reverse[m.href.split("/").pop()] ??= []).push({ title: body.match(/^# (.+)$/m)[1].trim(), href: `/${t.silo}/${t.slug}` });
}
for (const k of Object.keys(reverse)) reverse[k] = reverse[k].slice(0, 3);

fs.writeFileSync(path.join(root, "data/informational-guides.support.generated.ts"),
  `// AUTO-GENERATED by scripts/info-support/assemble.mjs - do not hand-edit.\nimport type { InformationalGuide } from "@/data/informational-guides";\n\nexport const supportInformationalGuides: InformationalGuide[] = ${JSON.stringify(entries, null, 2)};\n`);
fs.writeFileSync(path.join(root, "data/info-support-links.generated.ts"),
  `// AUTO-GENERATED by scripts/info-support/assemble.mjs - do not hand-edit.\n// Best-guide slug -> supporting explainers, rendered as "Learn before you buy" on RichGuidePage.\nexport const infoSupportLinks: Record<string, { title: string; href: string }[]> = ${JSON.stringify(reverse, null, 2)};\n`);
console.log(report.join("\n"));
console.log(`\npublished ${entries.length}, failed ${errors}, Best pages linked ${Object.keys(reverse).length}`);
if (errors && process.argv.includes("--strict")) process.exit(1);
